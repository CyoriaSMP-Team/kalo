public final class ResourcePackManagerImpl implements ResourcePackManager, Managerial, Reloadable {
    private static final Logger LOGGER = Logger.getLogger(ResourcePackManagerImpl.class.getName());

    private static final String PACK_DESCRIPTION = "Generated by " + Constants.PLUGIN_NAME;

    private io.kalo.pack.host.PackHost packHost;
    private io.kalo.pack.host.PackDeliveryListener delivery;
    private PackHostSettings packHostSettings;

    /** One builder prevents reload spam from running several CPU-heavy compilers at once. */
    private final ExecutorService packExecutor = Executors.newSingleThreadExecutor(
            Thread.ofPlatform().daemon(true).name("kalo-pack-builder", 0).factory());
    private final Object generationLock = new Object();
    private long requestedGeneration;
    private boolean generationWorkerRunning;
    private CompletableFuture<Void> generationFuture = CompletableFuture.completedFuture(null);

    @Override
    public void preload(@NotNull Context context) {
    }

    @Override
    public void start(@NotNull Context context) {
        reconfigurePackHost(context);
        generateResourcePack();
    }

    @Override
    public void end(@NotNull Context context) {
        stopPackHost();
    }

    /** Hot-reload path: keep an unchanged HTTP host alive so its URL/hash stay stable. */
    public void reloadManager(@NotNull Context context) {
        reconfigurePackHost(context);
        generateResourcePack();
    }

    /** Waits for a pack build before registries are torn down underneath it. */
    public void awaitIdle() {
        CompletableFuture<Void> future;
        synchronized (generationLock) {
            future = generationFuture;
        }
        future.join();
    }

    /** Final plugin shutdown, distinct from a Kalo content hot reload. */
    public void shutdown() {
        awaitIdle();
        packExecutor.shutdown();
        try {
            if (!packExecutor.awaitTermination(2, TimeUnit.SECONDS)) {
                packExecutor.shutdownNow();
            }
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
            packExecutor.shutdownNow();
        }
    }

    private void stopPackHost() {
        if (packHost != null) {
            packHost.stop();
            packHost = null;
        }
        if (delivery != null) {
            org.bukkit.event.HandlerList.unregisterAll(delivery);
            delivery = null;
        }
        packHostSettings = null;
    }

    /** Reconfigures the built-in host only when its settings actually changed. */
    private void reconfigurePackHost(@NotNull Context context) {
        org.bukkit.configuration.file.FileConfiguration config = context.plugin().getConfig();
        PackHostSettings desired = new PackHostSettings(
                config.getBoolean("pack-host.enabled", false),
                config.getInt("pack-host.port", 8163),
                config.getString("pack-host.public-address", "127.0.0.1"),
                config.getBoolean("pack-host.required", false));

        if (desired.equals(packHostSettings)
                && (!desired.enabled() || packHost != null)) {
            return;
        }

        stopPackHost();
        packHostSettings = desired;
        if (!desired.enabled()) {
            return;
        }

        packHost = new io.kalo.pack.host.PackHost(
                generatedPackFile(), desired.port(), desired.publicAddress());

        if (packHost.start()) {
            delivery = new io.kalo.pack.host.PackDeliveryListener(packHost, desired.required());
            Bukkit.getPluginManager().registerEvents(delivery, context.plugin());
        } else {
            packHost = null;
        }
    }

    private record PackHostSettings(boolean enabled, int port, @NotNull String publicAddress, boolean required) {
    }

    @Override
    public @NotNull CompletableFuture<Void> generateResourcePack() {
        synchronized (generationLock) {
            requestedGeneration++;
            if (!generationWorkerRunning) {
                generationWorkerRunning = true;
                generationFuture = CompletableFuture.runAsync(this::drainGenerationQueue, packExecutor);
            }
            return generationFuture;
        }
    }

    /**
     * Collapses any number of requests received during one build into a single follow-up
     * build. There is never more than one pack compiler touching CPU/disk at a time.
     */
    private void drainGenerationQueue() {
        while (true) {
            long targetGeneration;
            synchronized (generationLock) {
                targetGeneration = requestedGeneration;
            }

            try {
                buildResourcePack();
            } catch (Throwable throwable) {
                // A fire-and-forget CompletableFuture otherwise makes failures invisible.
                LOGGER.log(Level.SEVERE, "Resource pack generation failed", throwable);
            }

            synchronized (generationLock) {
                if (requestedGeneration == targetGeneration) {
                    generationWorkerRunning = false;
                    return;
                }
            }
        }
    }

    private void buildResourcePack() {
        LOGGER.info("Generating resource pack...");

        ResourcePack resourcePack = new ResourcePackImpl(
                PackMeta.of(PackFormats.resolve(), PACK_DESCRIPTION));

        copyPackAssets(resourcePack);
        compileContentTypes(resourcePack);
        compileRegistrylessTypes(resourcePack);
        mergeBasePack(resourcePack);

        if (bedrockWanted()) {
            generateBedrockPack(resourcePack);
        }

        RegistryManager.GlobalRegistries.registries().item().forEach(content ->
                content.featureEventBus().call(new ResourcePackGenerationEvent(resourcePack)));

        Bukkit.getPluginManager().callEvent(new AsyncResourcePackGenerationEvent(resourcePack));

        // After the event: a listener may have supplied the very asset that would
        // otherwise look missing.
        io.kalo.pack.PackValidator.report(io.kalo.pack.PackValidator.validate(resourcePack));

        final boolean changed;
        try {
            changed = ZipPackWriter.writeIfChanged(generatedPackFile(), resourcePack);
        } catch (Exception e) {
            LOGGER.log(Level.SEVERE, "Failed to write the generated resource pack", e);
            return;
        }

        if (changed) {
            LOGGER.info("Generated resource pack (" + resourcePack.files().size() + " files; output changed)");
        } else {
            LOGGER.info("Resource pack unchanged (" + resourcePack.files().size() + " files; keeping existing bytes/hash)");
        }

        io.kalo.pack.host.PackHost host = packHost;
        if (host != null) {
            if (changed) {
                // Only changed bytes get a new cache-busting URL and SHA-1.
                host.refresh();
            }
            LOGGER.info("Pack available at " + host.url());
        }
    }

    /**
     * Folds in a pack the server already ships, if one is configured.
     *
     * <p>After content compilation on purpose: Kalo's generated files must win on a
     * collision, since they are the half that has to agree with what the server sends.</p>
     */
    private static void mergeBasePack(@NotNull ResourcePack resourcePack) {
        String configured = Kalo.plugin() instanceof org.bukkit.plugin.java.JavaPlugin plugin
                ? plugin.getConfig().getString("base-pack", "")
                : "";
        if (configured == null || configured.isBlank()) {
            return;
        }

        File base = new File(configured);
        if (!base.isAbsolute()) {
            base = new File(Constants.dataFolder(), configured);
        }
        io.kalo.pack.PackMerger.merge(resourcePack, base);
    }

    private static @NotNull File generatedPackFile() {
        return new File(Constants.dataFolder(), "generated.zip");
    }

    /**
     * Builds the Bedrock pack and Geyser mapping alongside the Java pack.
     *
     * <p>The Java pack is passed in as a texture source only. A Bedrock pack has its own
     * layout and ignores the {@code assets/} tree entirely, so it gets its own container
     * rather than a copy of the Java one.</p>
     */
    /**
     * Whether to build Bedrock output at all.
     *
     * <p>A Java-only server has no use for a {@code .mcpack} or a Geyser mapping, and at
     * scale that is thousands of files written for nobody. Detected rather than asked for,
     * with an override because Geyser can also run as a separate process this cannot
     * see.</p>
     *
     * <p>{@code GeyserBridge} asks this too rather than reading the setting itself. Two
     * readers of one key drift: the bridge's copy treated anything but {@code never} as
     * yes, so {@code auto} on a server without Geyser meant one half was off and the other
     * on.</p>
     */
    public static boolean bedrockWanted() {
        String mode = Kalo.plugin() instanceof org.bukkit.plugin.java.JavaPlugin plugin
                ? plugin.getConfig().getString("bedrock", "auto")
                : "auto";

        return switch (mode == null ? "auto" : mode.toLowerCase(java.util.Locale.ROOT)) {
            case "always", "true" -> true;
            case "never", "false" -> false;
            // "auto": build it when Geyser is here to consume it.
            default -> io.kalo.integration.GeyserIntegration.present();
        };
    }

    private static void generateBedrockPack(@NotNull ResourcePack javaPack) {
        Registries registries = RegistryManager.GlobalRegistries.registries();

        // Native Java carrier assignments are exported for the Geyser mapping; virtual
        // blocks intentionally have no finite state and are labelled by
        // BedrockPackCompiler. The whole assignment travels, carrier included — the state
        // index means nothing without the carrier it was allocated from.
        java.util.Map<net.kyori.adventure.key.Key, io.kalo.platform.java.BlockStateAllocator.Assignment>
                blockStates = new java.util.HashMap<>();
        if (Kalo.plugin().registryManager() instanceof RegistryManagerImpl impl) {
            impl.blockStateAllocator().assignments().forEach((key, assignment) ->
                    blockStates.put(net.kyori.adventure.key.Key.key(key), assignment));
        }

        ResourcePack bedrock = new ResourcePackImpl(PackMeta.of(0, PACK_DESCRIPTION));
        BedrockPackCompiler compiler = new BedrockPackCompiler(javaPack, bedrock);

        // One compiler across every content type: writing the manifest and mapping per
        // type meant the last one to run erased the others' mappings.
        compiler.add(registries.item());
        compiler.add(registries.armor());
        // Armor needs an attachable on top of its icon, or Bedrock draws the base
        // material's armor instead of the custom one.
        compiler.addArmor(registries.armor());
        // Skips whatever the Java compiler could not place, so the two platforms cannot
        // drift apart on which blocks exist.
        java.util.Set<String> blockSkip = java.util.Set.of();
        java.util.Set<String> furnitureSkip = java.util.Set.of();
        if (Kalo.plugin().registryManager() instanceof RegistryManagerImpl impl) {
            blockSkip = impl.registries().types().get(io.kalo.content.block.BlockType.KEY)
                    .filter(io.kalo.content.block.BlockType.class::isInstance)
                    .map(io.kalo.content.block.BlockType.class::cast)
                    .map(io.kalo.content.block.BlockType::uncompilable)
                    .orElse(java.util.Set.of());
            furnitureSkip = impl.registries().types().get(io.kalo.content.furniture.FurnitureType.KEY)
                    .filter(io.kalo.content.furniture.FurnitureType.class::isInstance)
                    .map(io.kalo.content.furniture.FurnitureType.class::cast)
                    .map(io.kalo.content.furniture.FurnitureType::uncompilable)
                    .orElse(java.util.Set.of());
        }

        compiler.addBlocks(registries.block(), blockStates::get, blockSkip);
        compiler.addBlocks(registries.furniture(), blockStates::get, furnitureSkip);

        BedrockPackCompiler.Result result = compiler.finish();

        try {
            BedrockPackWriter.write(new File(Constants.dataFolder(), "generated.mcpack"), result.pack().files());

            // Geyser's own custom_mappings format, so a separate Geyser process needs no
            // Kalo artifact inside it — copy these two files and its packs/ folder and it
            // registers everything itself. Items and blocks version separately
            // (format_version 2 and 1), which is why they cannot share one file.
            File geyser = new File(Constants.dataFolder(), "geyser");
            java.nio.file.Files.createDirectories(geyser.toPath());
            java.nio.file.Files.write(new File(geyser, "kalo-items.json").toPath(),
                    result.itemMappings().toByteArray());
            java.nio.file.Files.write(new File(geyser, "kalo-blocks.json").toPath(),
                    result.blockMappings().toByteArray());
        } catch (Exception e) {
            LOGGER.log(Level.SEVERE, "Failed to write Bedrock output", e);
            // Say so, or Geyser blocks its palette event for the full timeout waiting for
            // output that is never coming.
            BedrockRegistrationSnapshot.publishFailure(result.generation());
            return;
        }

        // The output is durable, so the native Geyser bridge may now register against it.
        // Nothing published this until now: GeyserBridge waited out its timeout on every
        // startup and registered no blocks at all, which is why custom blocks never
        // reached a Bedrock client.
        BedrockRegistrationSnapshot.publishSuccess(result.generation(), result.registrations());

        // mappedCount is distinct vanilla items, which reads like a failure when 1000
        // custom items all map onto PAPER. Report what the reader actually wants.
        LOGGER.info("Generated Bedrock pack: " + result.itemCount() + " item(s) across "
                + result.mappedCount() + " vanilla item(s), " + result.blockCount() + " block(s), "
                + result.armorCount() + " worn armor piece(s), "
                + result.pack().files().size() + " file(s)");
        if (result.skippedCount() > 0) {
            // Said out loud rather than silently dropped: a pack author who sees their
            // item on Java but not on Bedrock deserves to know why.
            LOGGER.warning(result.skippedCount() + " item(s) were left out of the Bedrock pack because they use a "
                    + "custom model; Bedrock geometry conversion is not implemented yet");
        }
    }

    /**
     * Copies each pack's {@code assets/} directory into the generated pack under its own
     * namespace, so textures and hand-authored models ship alongside generated JSON.
     */
    private static void copyPackAssets(@NotNull ResourcePack resourcePack) {
        for (Pair<net.kyori.adventure.key.Key, ContentsPack> entry
                : RegistryManager.GlobalRegistries.registries().contentsPacks().entries()) {
            ContentsPack pack = entry.value();
            File assetsFolder = new File(pack.packFolder(), "assets");
            if (!assetsFolder.isDirectory()) {
                continue;
            }

            for (File asset : Files.listFilesRecursively(assetsFolder)) {
                String relative = assetsFolder.toPath().relativize(asset.toPath()).toString().replace('\\', '/');
                resourcePack.file("assets/" + pack.id() + "/" + relative, Writable.file(asset));
            }
        }
    }

    /**
     * Compiles the types that keep their own content rather than a registry.
     *
     * <p>{@link #compileContentTypes} walks the registries and skips a type with nothing
     * in them — which is every time for sounds and glyphs, since neither produces
     * {@code Content}. Without this they would silently never reach the pack.</p>
     */
    private static void compileRegistrylessTypes(@NotNull ResourcePack resourcePack) {
        if (Kalo.plugin().registryManager() instanceof RegistryManagerImpl impl) {
            impl.soundType().compile(resourcePack);
            impl.glyphType().compile(resourcePack);
        }
    }

    /** Lets every registered content type contribute its own assets. */
    @SuppressWarnings("unchecked")
    private static void compileContentTypes(@NotNull ResourcePack resourcePack) {
        for (Pair<net.kyori.adventure.key.Key, ContentType<?>> entry
                : RegistryManager.GlobalRegistries.registries().types().entries()) {
            ContentType<Content> type = (ContentType<Content>) entry.value();

            List<Content> contents = new ArrayList<>();
            Registries registries = RegistryManager.GlobalRegistries.registries();
            for (Content content : type.contents(registries)) {
                if (type.clazz().isInstance(content)) {
                    contents.add(content);
                }
            }

            if (!contents.isEmpty()) {
                type.compilePack(resourcePack, contents);
            }
        }
    }

    /** Sends the per-content extension event to every content type, not only items. */
    static void dispatchFeatureEvents(@NotNull ResourcePack resourcePack,
                                      @NotNull RegistryManager.GlobalRegistries registries) {
        Set<Content> seen = Collections.newSetFromMap(new IdentityHashMap<>());
        ResourcePackGenerationEvent event = new ResourcePackGenerationEvent(resourcePack);

        for (Pair<net.kyori.adventure.key.Key, ContentType<?>> entry : registries.types().entries()) {
            try {
                for (Object candidate : entry.value().contents(registries)) {
                    if (!(candidate instanceof Content content) || !seen.add(content)) {
                        continue;
                    }
                    try {
                        content.featureEventBus().call(event);
                    } catch (RuntimeException e) {
                        LOGGER.log(Level.WARNING, "A resource-pack feature failed for content '"
                                + content.key().asString() + "'", e);
                    }
                }
            } catch (RuntimeException e) {
                LOGGER.log(Level.WARNING, "Could not enumerate content type '"
                        + entry.key().asString() + "' for resource-pack feature events", e);
            }
        }
    }

    /**
     * Serializes generations and provides a lifecycle barrier for reload/shutdown.
     *
     * <p>The old implementation launched every request independently on the common pool.
     * Two quick reloads could therefore write the same zip concurrently, while the older
     * task could refresh the newer host with a hash for whichever write happened to win.</p>
     */
    static final class GenerationQueue {
        private final Executor executor;
        private CompletableFuture<Void> tail = CompletableFuture.completedFuture(null);
        private boolean accepting;

        GenerationQueue(@NotNull Executor executor) {
            this.executor = executor;
        }

        synchronized void start() {
            accepting = true;
        }

        synchronized @NotNull CompletableFuture<Void> submit(@NotNull Runnable generation) {
            if (!accepting) {
                return CompletableFuture.failedFuture(
                        new IllegalStateException("Resource pack manager is not running"));
            }

            // A failed generation must not poison the queue forever; the next explicit
            // request still deserves a chance to rebuild after the underlying issue is fixed.
            tail = tail.handle((ignored, failure) -> null).thenRunAsync(generation, executor);
            return tail;
        }

        void stopAndWait() {
            CompletableFuture<Void> pending;
            synchronized (this) {
                accepting = false;
                pending = tail;
            }
            try {
                pending.join();
            } catch (CompletionException ignored) {
                // generateResourcePack's completion handler already logged the cause.
            }
        }
    }
}
